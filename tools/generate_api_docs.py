_modules = {}
EXPORT_MODULES = {
    'imzdesk.core',
    'imzdesk.data',
    'imzdesk.io',
    'imzdesk.transforms',
    'imzdesk.visualization',
}


def load_module(name):
    """
    Load and cache a module for static documentation analysis.
    """
    if name not in _modules:
        _modules[name] = load(
            name,
            search_paths=[SOURCE],
            docstring_parser='numpy',
        )
    return _modules[name]


def resolve(symbol):
    """
    Resolve a configured symbol to its defining Griffe object.
    """
    try:
        member = load_module(symbol.module)[symbol.name]
    except KeyError as exception:
        raise RuntimeError(f'Could not find documented symbol {symbol.path}.') from exception
    return member.target if member.is_alias else member


def clean_inline(value):
    """
    Normalize inline reStructuredText for Markdown output.
    """
    if value is None:
        return ''
    text = str(value).strip().replace('``', '`')
    return re.sub(r'\s+', ' ', text)


def clean_text(value):
    """
    Normalize wrapped docstring prose while preserving paragraphs.
    """
    paragraphs = re.split(r'\n\s*\n', str(value).strip())
    return '\n\n'.join(
        textwrap.fill(clean_inline(paragraph), width=80)
        for paragraph in paragraphs
        if paragraph.strip()
    )


def annotation(value):
    """
    Return a normalized display value for a type expression.
    """
    if type(value).__name__ == 'ExprTuple':
        elements = []
        for element in value.elements:
            item = clean_inline(element)
            literal = item in {'None', 'True', 'False'} or item.replace('.', '', 1).isdigit()
            elements.append(item if literal else repr(item))
        return f'{{{", ".join(elements)}}}'
    return (clean_inline(value) or 'Any').replace(' - ', '-')


def signature_line(object_, path, *, class_=False):
    """
    Format a public path with an object's source signature.
    """
    signature = object_.signature()
    opening = signature.find('(')
    parameters = signature[opening:] if opening >= 0 else ''
    prefix = 'class ' if class_ else ''
    line = f'{prefix}{path}{parameters}'
    if len(line) <= 80 or not parameters:
        return line

    arguments = split_arguments(parameters[1:-1])
    if len(arguments) <= 1:
        return line
    body = ',\n'.join(f'    {argument}' for argument in arguments)
    return f'{prefix}{path}(\n{body},\n)'


def split_arguments(parameters):
    """
    Split a signature argument list without splitting nested expressions.
    """
    if not parameters:
        return []
    arguments = []
    start = 0
    depth = 0
    quote = None
    escaped = False
    for index, character in enumerate(parameters):
        if quote is not None:
            if escaped:
                escaped = False
            elif character == '\\':
                escaped = True
            elif character == quote:
                quote = None
            continue
        if character in {'\'', '"'}:
            quote = character
        elif character in '([{':
            depth += 1
        elif character in ')]}':
            depth -= 1
        elif character == ',' and depth == 0:
            arguments.append(parameters[start:index].strip())
            start = index + 1
    arguments.append(parameters[start:].strip())
    return [argument for argument in arguments if argument]


def docstring_for(object_):
    """
    Return an object's docstring or its constructor docstring.
    """
    if object_.docstring is not None:
        return object_.docstring
    if object_.is_class and '__init__' in object_.members:
        return object_.members['__init__'].docstring
    return None


def render_list_section(title, values, *, include_name=True):
    """
    Render a structured docstring section as a Markdown list.
    """
    lines = [f'**{title}**', '']
    for value in values:
        name = clean_inline(getattr(value, 'name', ''))
        type_name = annotation(getattr(value, 'annotation', None))
        description = clean_inline(getattr(value, 'description', ''))
        if include_name and name:
            subject = f'`{name}` (`{type_name}`)'
        else:
            subject = f'`{type_name}`'
        item = f'- {subject}: {description}' if description else f'- {subject}'
        lines.extend(textwrap.wrap(item, width=80, subsequent_indent='  ', break_long_words=False))
    lines.append('')
    return lines


def render_docstring(docstring, *, skip_attributes=False):
    """
    Render parsed NumPy docstring sections as Markdown.
    """
    if docstring is None:
        return []
    lines = []
    for section in docstring.parsed:
        kind = section.kind
        if kind is DocstringSectionKind.text:
            text = clean_text(section.value)
            if text:
                lines.extend([text, ''])
        elif kind in {DocstringSectionKind.parameters, DocstringSectionKind.other_parameters}:
            lines.extend(render_list_section('Parameters', section.value))
        elif kind is DocstringSectionKind.attributes:
            if not skip_attributes:
                lines.extend(render_list_section('Attributes', section.value))
        elif kind is DocstringSectionKind.raises:
            lines.extend(render_list_section('Raises', section.value, include_name=False))
        elif kind is DocstringSectionKind.warns:
            lines.extend(render_list_section('Warnings', section.value, include_name=False))
        elif kind is DocstringSectionKind.returns:
            lines.extend(render_list_section('Returns', section.value))
        elif kind is DocstringSectionKind.yields:
            lines.extend(render_list_section('Yields', section.value))
        elif kind is DocstringSectionKind.admonition:
            title = section.title or 'Note'
            description = clean_text(section.value.description)
            lines.extend([f'**{title}**', '', description, ''])
        else:
            raise RuntimeError(f'Unsupported docstring section: {kind.value}.')
    return lines


def documented_members(class_):
    """
    Yield documented public methods and properties from a class.
    """
    for name, member in class_.members.items():
        if name == '__init__':
            continue
        if name.startswith('_') and name not in PUBLIC_DUNDERS:
            continue
        if member.kind.value == 'function' or 'property' in member.labels:
            if member.docstring is None:
                raise RuntimeError(f'Public member {class_.path}.{name} has no docstring.')
            yield name, member


def render_fields(class_):
    """
    Render explicitly annotated class and instance fields.
    """
    fields = [
        (name, member)
        for name, member in class_.members.items()
        if not name.startswith('_')
        and member.kind.value == 'attribute'
        and 'property' not in member.labels
        and member.annotation is not None
    ]
    if not fields:
        return []

    descriptions = {}
    docstring = docstring_for(class_)
    if docstring is not None:
        for section in docstring.parsed:
            if section.kind is DocstringSectionKind.attributes:
                descriptions.update({value.name: clean_inline(value.description) for value in section.value})

    lines = ['**Fields**', '']
    for name, field in fields:
        type_name = annotation(field.annotation)
        description = descriptions.get(name, '')
        subject = f'`{name}` (`{type_name}`)'
        item = f'- {subject}: {description}' if description else f'- {subject}'
        lines.extend(textwrap.wrap(item, width=80, subsequent_indent='  ', break_long_words=False))
    lines.append('')
    return lines


def render_member(public_class_path, name, member):
    """
    Render one class method or property.
    """
    lines = [f'### {name}', '']
    path = f'{public_class_path}.{name}'
    if 'property' in member.labels:
        lines.extend(['```text', f'property {path}', '```', ''])
    else:
        qualifiers = []
        if 'classmethod' in member.labels:
            qualifiers.append('classmethod')
        if 'staticmethod' in member.labels:
            qualifiers.append('staticmethod')
        if 'abstractmethod' in member.labels:
            qualifiers.append('abstract')
        line = signature_line(member, path)
        if qualifiers:
            line = f'{", ".join(qualifiers)} {line}'
        lines.extend(['```text', line, '```', ''])
    lines.extend(render_docstring(member.docstring))
    return lines


def render_symbol(symbol):
    """
    Render one configured public symbol and its members.
    """
    object_ = resolve(symbol)
    lines = [f'## {symbol.name}', '', '```text']
    if object_.is_class:
        lines.append(signature_line(object_, symbol.path, class_=True))
    elif object_.is_function:
        lines.append(signature_line(object_, symbol.path))
    else:
        raise RuntimeError(f'Unsupported symbol kind for {symbol.path}: {object_.kind.value}.')
    lines.extend(['```', ''])

    docstring = docstring_for(object_)
    if docstring is None:
        raise RuntimeError(f'Public symbol {symbol.path} has no docstring.')
    fields = render_fields(object_) if object_.is_class else []
    lines.extend(render_docstring(docstring, skip_attributes=bool(fields)))

    if object_.is_class:
        lines.extend(fields)
        for name, member in documented_members(object_):
            lines.extend(render_member(symbol.path, name, member))
    return lines


def render_page(page):
    """
    Render one configured API reference page.
    """
    lines = [GENERATED_NOTICE, '', f'# {page.title}', '', clean_text(page.introduction), '']
    for symbol in page.symbols:
        lines.extend(render_symbol(symbol))
    return '\n'.join(lines).rstrip() + '\n'


