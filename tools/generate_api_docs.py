def validate_manifest():
    """
    Verify that configured package exports are documented exactly once.
    """
    for module_name in EXPORT_MODULES:
        module = load_module(module_name)
        exported = {
            name
            for name, member in module.members.items()
            if not name.startswith('_') and member.kind.value in {'class', 'function'}
        }
        documented = {
            symbol.name
            for page in PAGES
            for symbol in page.symbols
            if symbol.module == module_name
        }
        missing = exported - documented
        extra = documented - exported
        if missing or extra:
            details = []
            if missing:
                details.append(f'missing {sorted(missing)}')
            if extra:
                details.append(f'unknown {sorted(extra)}')
            raise RuntimeError(f'Invalid API manifest for {module_name}: {"; ".join(details)}.')

    registration = load_module('imzdesk.registration')
    exported_functions = {
        name
        for name, member in registration.members.items()
        if not name.startswith('_') and member.kind.value == 'function'
    }
    documented_functions = {
        symbol.name
        for page in PAGES
        for symbol in page.symbols
        if symbol.module == 'imzdesk.registration'
    }
    if exported_functions != documented_functions:
        raise RuntimeError('The registration API manifest does not match its public functions.')


def generated_files():
    """
    Return every generated path and its expected content.
    """
    files = {
        DOCS / 'README.md': render_index(),
        DOCS / 'transforms' / 'README.md': render_transforms_index(),
    }
    files.update({DOCS / page.output: render_page(page) for page in PAGES})
    return files


def write_files(files):
    """
    Write generated documentation files to disk.
    """
    for path, content in files.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding='utf-8')


def check_files(files):
    """
    Raise an error when committed API reference files are stale.
    """
    stale = [
        str(path.relative_to(ROOT))
        for path, content in files.items()
        if not path.is_file() or path.read_text(encoding='utf-8') != content
    ]
    if stale:
        paths = '\n'.join(f'- {path}' for path in stale)
        raise RuntimeError(f'Generated API documentation is stale:\n{paths}')


def main():
    """
    Generate the API reference or verify the committed output.
    """
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='verify that generated files are current')
    args = parser.parse_args()

    validate_manifest()
    files = generated_files()
    check_files(files) if args.check else write_files(files)


if __name__ == '__main__':
    main()
