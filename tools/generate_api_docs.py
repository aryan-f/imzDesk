@dataclass(frozen=True)
class Symbol:
    module: str
    name: str
    public_module: str | None = None

    @property
    def path(self):
        """
        Return the symbol's public import path.
        """
        return f'{self.public_module or self.module}.{self.name}'


@dataclass(frozen=True)
class Page:
    output: str
    title: str
    introduction: str
    symbols: tuple[Symbol, ...]


def symbols(module, *names, public_module=None):
    """
    Construct a tuple of documented symbols from one module.
    """
    return tuple(Symbol(module, name, public_module) for name in names)


